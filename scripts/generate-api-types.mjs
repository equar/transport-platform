// Generate matching web/mobile contracts from a running local/dev OpenAPI endpoint or a saved specification.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const source = process.argv[2] ?? 'http://localhost:8087/api/v3/api-docs';
const spec = /^https?:/.test(source) ? await (await fetch(source)).json() : JSON.parse(await readFile(source, 'utf8'));
function type(s = {}) {
  if (s.$ref) return s.$ref.split('/').at(-1).replace(/[^\w$]/g, '_');
  if (s.enum) return s.enum.map(v => JSON.stringify(v)).join(' | ');
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(type).join(' | ');
  if (s.allOf) return s.allOf.map(type).join(' & ');
  const t = s.type === 'integer' || s.type === 'number' ? 'number' : s.type === 'boolean' ? 'boolean' : s.type === 'array' ? `Array<${type(s.items)}>` : s.type === 'object' || s.properties ? `{ ${Object.entries(s.properties ?? {}).map(([k,v]) => `${JSON.stringify(k)}${s.required?.includes(k) ? '' : '?'}: ${type(v)}`).join('; ')}${s.additionalProperties ? `; [key: string]: ${typeof s.additionalProperties === 'object' ? type(s.additionalProperties) : 'unknown'}` : ''} }` : s.type === 'string' ? 'string' : 'unknown';
  return s.nullable ? `${t} | null` : t;
}
const output = '// Generated by scripts/generate-api-types.mjs. Do not edit.\n' + Object.entries(spec.components?.schemas ?? {}).sort(([a],[b]) => a.localeCompare(b)).map(([name,schema]) => `export type ${name.replace(/[^\w$]/g,'_')} = ${type(schema)};`).join('\n') + '\n';
for (const directory of ['frontend/src/shared/api/generated', 'mobile/src/api/generated']) {
  await mkdir(directory, { recursive: true }); await writeFile(`${directory}/contracts.ts`, output);
}
console.log('Generated shared API contracts for web and mobile.');
